"""タイトル文字列の正規化と、機種・グレードの判定（名寄せの中核）。"""

import re
import unicodedata

from .spec import ModelSpec, Grade


def normalize(text: str) -> str:
    """表記ゆれを吸収するための正規化。

    - NFKC で全角英数・半角カナなどを統一（パラダイム等の全角→半角、ﾊﾟﾗﾀﾞｲﾑ→パラダイム）
    - 小文字化
    - 連続空白の圧縮
    - 前後に空白を付与（' dr ' のような単語境界マッチをしやすくする）
    """
    if not text:
        return " "
    t = unicodedata.normalize("NFKC", text)
    t = t.lower()
    # 記号類を空白に（◆ は判定に使うので残す。〜はアイアン番手レンジに使うので残す）
    t = re.sub(r"[【】\[\]（）()｜|/／,，･・’'\"”“★☆●○◎■□‼]", " ", t)
    t = re.sub(r"\s+", " ", t)
    return f" {t.strip()} "


def _has_any(norm_title: str, aliases: list[str]) -> bool:
    for a in aliases:
        a = a.strip().lower()
        if a == "":
            return True  # 空エイリアスは常に真（フォールバック用）
        if a in norm_title:
            return True
    return False


def is_target_model(norm_title: str, spec: ModelSpec) -> bool:
    """この機種かどうか（ブランド・モデル・シリーズ・種別が全て揃うか）。"""
    if spec.excludes and _has_any(norm_title, spec.excludes):
        return False
    return (
        _has_any(norm_title, [normalize(x).strip() for x in spec.brand])
        and _has_any(norm_title, [normalize(x).strip() for x in spec.model])
        and _has_any(norm_title, [normalize(x).strip() for x in spec.series])
        and _has_any(norm_title, [normalize(x).strip() for x in spec.club_type])
    )


def classify_grade(norm_title: str, spec: ModelSpec) -> Grade:
    """グレードを判定（spec.grades の順に評価し最初に当たったもの）。"""
    for g in spec.grades:
        if g.excludes and _has_any(norm_title, [normalize(x).strip() for x in g.excludes]):
            continue
        if _has_any(norm_title, [normalize(x).strip() if x else "" for x in g.aliases]):
            return g
    return spec.grades[-1]


# シャフト有無の判定。メルカリは「〜ドライバー ヘッド」「〜ヘッド 9.0度」のように
# 「のみ」を書かないヘッド単体出品が多いため、タイトル末尾の「ヘッド」、
# 「ヘッド＋付属品」、「ヘッド ＋ロフト度数」も拾う
# （「ヘッドカバー」「ヘッドに傷」「ヘッドスピード」等は拾わない）。
_HEAD_ONLY_PAT = re.compile(
    # のみ/単体等の前のスペースも許容（2026-07-09: 「ヘッド 単体」がすり抜けた）
    # 2026-08-15すり抜け分: 中古ショップのテンプレートは**カタカナ**で書く。
    # 「ピン G410 Hybrid/ヘッドノミ レンチナシ」（ゴルフマンモス・楽天の最安11,338円）
    # 「テーラーメイド P790 UDI 2019◆ヘッドノミ◆」など。ひらがなの「のみ」しか
    # 見ていなかったため、店の在庫がまるごと素通りしていた
    r"ヘッド\s*(のみ|ノミ|単体|単品|だけ|オンリー)|head\s*only"
    r"|ヘッド\s*[+＋]|ヘッド\s*$|ヘッド\s*本体"
    r"|ヘッド\s*(?=[0-9.]{1,4}\s*[°度])"
    # 2026-08-01すり抜け分:「SIM2max ドライバー 10.5°ヘッド テーラーメイド」。
    # 上のパターンは「ヘッド→ロフト」順しか拾えず、逆順の「ロフト→ヘッド」が漏れた。
    # 完品の「10.5度 ヘッドカバー付」を落とさないようカバー/スピードは除外
    r"|[0-9.]{1,4}\s*[°度]\s*ヘッド(?!カバー|スピード)"
    # 2026-08-09すり抜け分: 「Qi10 10.5 ドライバー ヘッド 検索)Qi10 Qi35 LS ステルス」。
    # クラブ種別の直後に単独トークンの「ヘッド」が来る形（後ろが検索タグ等で終端でない）。
    # 完品の「ドライバー ヘッドカバー付」「ヘッドスピード」は除外
    r"|(ドライバー|フェアウェイウッド|ウッド|ユーティリティ|レスキュー|アイアン)\s+ヘッド(?!カバー|スピード)"
    # 「〜ドライバー ヘッド 10.5」のような度なし裸ロフトで終わるタイトル
    # （2026-07-08: ROGUE ST MAX がこの形ですり抜けて割安リストに混入）
    r"|ヘッド\s*[0-9.]{1,4}\s*$"
    # 2026-07-31すり抜け分: 「PRGR RS X MAX ドライバー ヘッド 純正ヘッドカバー付属」。
    # 単独トークンの「ヘッド」＋「ヘッドカバー」＝ヘッド本体とカバーの2点を並記した単品出品。
    # 完品は「ドライバー ヘッドカバー付」と書き、ヘッド直後は必ずカバーに続くため誤検出しない
    r"|ヘッド\s+(純正|専用|未使用|新品)*\s*ヘッドカバー"
    # 2026-08-03: 「ヘッド」の誤字「ベッド/ベット」。2回目の観測（7/29 G440「ベットのみ」、
    # 8/3 Qi35 MAX「ドライバーベッドのみ」）。誤字なので既存パターンを全部すり抜ける。
    # 一般名詞の「ベッド」を拾わないよう、のみ/単体等 または クラブ種別直後 に限定
    r"|ベッ[ドト]\s*(のみ|単体|単品|だけ)"
    r"|(ドライバー|フェアウェイウッド|ウッド|ユーティリティ|レスキュー|アイアン)\s*ベッ[ドト]"
    r"|シャフトなし|シャフト無し|シャフト欠品")


def detect_head_only(norm_title: str) -> bool:
    return bool(_HEAD_ONLY_PAT.search(norm_title))


# 説明文用のヘッド単品判定。タイトルは実クラブ風でも説明文にだけ
# 「ヘッド単品販売です」「ヘッド及びヘッドカバーの出品」「シャフトは付属しません」
# と書かれる出品が多い（2026-07-08: 割安候補6件中3件がこのパターン）。
# 逆パターンのシャフト単品（ヘッドなし）も同じ穴なのでここで拾う
# （2026-07-09: エリートミニのシャフト単品がLINE通知をすり抜けた）。
# 通知や本命抽出の最終フィルタ用で、多少の過剰検出は許容する。
_HEAD_ONLY_DESC_PAT = re.compile(
    # 2026-08-12 誤検出修正: 完品が「ヘッドのみ付け替えて数回ラウンド使用」と
    # 書くケースを単品と誤判定していた（m37322832258 = Qi10 MAX 完品33,000円・
    # 純正Diamana TM50装着・カバー付を★単品と判定）。「ヘッドのみ」は商品範囲の
    # 宣言だけでなく「ヘッドだけ交換した」という作業の説明にも使われる。
    # 直後に 替/換/磨/拭 が来る＝出品者が自分のクラブに施した作業の話なので除外。
    # 「ヘッドのみ交換用」は本物の単品なので 用 が続く場合は除外しない
    r"ヘッド\s*(のみ|単体|単品|だけ)(?![^。\n]{0,6}([替換](?!用)|磨|拭))"
    r"|ヘッド(及び|および|と)ヘッドカバー"
    # 「ヘッドカバー付きの出品です」（完品）を誤検出しないよう「カバー付」は除く
    # （2026-07-11: Qi10 MAX完品風ヘッド単品の検死中に誤検出と判明。
    #   なお当該出品は本当にヘッド単品だった＝説明文無言型。写真確認が最終防衛線）
    r"|ヘッド(?!カバー[付つ])[^。\n]{0,10}の?出品"
    r"|シャフト[^。\n]{0,25}付属(しません|致しません|いたしません|なし|無し)"
    r"|シャフトは(付き|附属|付属)ません"
    r"|シャフト\s*(のみ|単体|単品|だけ)\s*の?\s*(出品|販売|発送|送付)"
    r"|ヘッド[^。\n]{0,10}(付属|附属)(しません|致しません|いたしません|なし|無し)"
    # 2026-07-12すり抜け分: 「〜のヘッドと付属品になります」(TSR2)、
    # 「シャフト付きが良い方はコメントしてください」(SIM2 MAX、ベースはヘッド単品)
    r"|ヘッドと付属品"
    r"|シャフト付きが(良い|よい|いい)方"
    r"|シャフトは?別(売|途)"
    # 2026-07-16すり抜け分: シャフト単品が「GT2フェアウェイウッド」風タイトルで
    # 出品され、説明文に「チップカット0.5インチ」「バットカットで5w 7wも使用可能」。
    # チップ/バットカットはシャフト単品・加工出品の語。「チップカットなし」（完品）は除外
    r"|(チップ|バット)カット(?!は?(なし|無し|して(い)?ません))"
    # 2026-07-18すり抜け分: 「シャフトのみ105.9センチ」（Ventus Black×G440題名の
    # シャフト単品）。既存パターンは「シャフトのみ+出品/販売」の語順しか拾えなかった。
    # 数字が直後に続く長さ表記形のみ対象（「シャフトのみの長さ」= 完品のスペック記述は除外）
    r"|シャフト\s*(のみ|単体|単品|だけ)\s*[0-9０-９]{2,3}(\.[0-9０-９])?\s*(センチ|cm|㎝)"
    # 2026-07-26すり抜け分（シャフト単品／折れシャフト）:
    # ・「◯番に付属していたものを即抜きしました」= クラブからシャフトを引き抜いた単品
    r"|即\s*抜き"
    # ・「ドライバーシャフト 純正品 M6に付いていたものです」= 複合名詞のシャフト単品。
    #   完品の「純正ドライバーシャフト装着」等を誤検出しないよう、直後が
    #   純正/のみ/単品/です/区切り のときだけ（＝製品としてのシャフト言及）に限定
    r"|(ドライバー|フェアウェイウッド|ウッド|ユーティリティ|レスキュー)シャフト\s*(純正|のみ|単体|単品|です|、|。|$)"
    # ・「シャフトが折れてしまい」= 折れシャフト個体（ヘッド＋折れ＝クリーン完品でない）。
    #   「折れにくいシャフト」(耐久アピール完品)を誤検出しないよう完了形のみ
    r"|シャフトが?折れ(て|た|ちゃ)"
    # 2026-08-03: 誤字「ベッド/ベット」（タイトル側と同趣旨）
    r"|ベッ[ドト]\s*(のみ|単体|単品|だけ)"
    r"|(ドライバー|フェアウェイウッド|ウッド|ユーティリティ|レスキュー|アイアン)\s*ベッ[ドト]"
    # 2026-08-09すり抜け: AIテンプレの「- タイプ: ドライバーヘッド」（m85921493855）。
    # 商品種別として「◯◯ヘッド」を宣言する形。完品が「ドライバーのヘッド部分に凹み」等と
    # 書くケースを巻き込まないよう、種別ラベル直後に限定する
    r"|タイプ\s*[:：]?\s*"
    r"(ドライバー|フェアウェイウッド|ウッド|ユーティリティ|レスキュー|アイアン|1w|fw|ut)?"
    r"\s*ヘッド(?!カバー)")


# 2026-07-18すり抜け分その2: AIテンプレ説明文の「〜なCallaway ELYTEドライバーヘッドです」。
# 商品を「◯◯ヘッド」と呼ぶ説明文はヘッド単品率が極めて高い（完品なら「ドライバーです」と書く）。
# 「ヘッドカバーです」は ヘッド直後の です 必須のため誤検出しない
# 2026-08-01すり抜け分:「Callaway ELYTE ドライバーのヘッドです。」＝「の」が挟まる形。
# 助詞ありなし両対応にする
# 2026-08-12すり抜け分: 「カーボンフェースを採用したTaylorMadeのドライバーヘッドで、
# 高い反発性能と…」（m35311403449 = ステルス9° 11,800円・写真5枚すべてヘッドのみで
# ホーゼルが空いていた）。同じAIテンプレの文が「です」で終わらず読点で続く形。
# 完品96件のコーパスで誤検出0件を確認済み（scripts/desc_corpus.py diff）
_HEAD_NOUN_DESC_PAT = re.compile(
    r"(ドライバー|フェアウェイウッド|ウッド|ユーティリティ|レスキュー|アイアン)"
    r"\s*の?\s*ヘッド(です|で[、,])")

# 2026-07-30 誤検出修正: 上のAIテンプレは完品でも冒頭でヘッドの構造だけを語る
# （G440 MAX完品 m18965284911:「…を追求したドライバーヘッドです。」の後に
#  「シャフト:ping tour chrome2.0 65s」と装着シャフトを明記）。
# 装着シャフトの型番が書かれている＝完品なので「◯◯ヘッドです」単独では落とさない。
# 「シャフト:なし」等の否定形では抑止しない（ヘッド単品を取りこぼさないため）
_SHAFT_SPEC_PAT = re.compile(
    r"シャフト\s*:\s*(?!(なし|無し|ありません|付属|別売|別途|欠品|不明))\S")


def detect_head_only_desc(norm_desc: str) -> bool:
    """説明文から部品単品出品（ヘッドのみ／シャフトのみ）を検出。
    normalize() 済みの文字列を渡す。"""
    if _HEAD_ONLY_DESC_PAT.search(norm_desc):
        return True
    return bool(_HEAD_NOUN_DESC_PAT.search(norm_desc)
                and not _SHAFT_SPEC_PAT.search(norm_desc))


# レフティ（左用）は市場が別で相場も薄い。右用の相場・候補に混ぜない
