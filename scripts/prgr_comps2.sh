run "新品 PRGR 全般(参考)"        "プロギア 新品 ドライバー フェアウェイ"   "prgr,新品"     "パター,バッグ,グローブ,ボール,ウェア,レディ"

# ---- ② RS FW 7W の世代分割 ----
