# ---- ⑤ SUPER EGG DR 2024 ----
run "SUPER EGG DR 2024"          "プロギア スーパーエッグ ドライバー 2024" "superegg,2024" "アイアン,ユーティリティ,フェアウェイ,レディース"
run "SUPER EGG UT"               "プロギア スーパーエッグ ユーティリティ"  "superegg,ut"   "アイアン,ドライバー,フェアウェイ,レディース"

# ---- ⑥ レディース 05 アイアンセット ----
run "PRGR レディース アイアンセット" "プロギア レディース アイアン セット"  "prgr,レディ"   "単品,ウェッジ,ドライバー,パター,フェアウェイ,ユーティリティ"
