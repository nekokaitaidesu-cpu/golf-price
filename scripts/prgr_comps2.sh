run "SWEEP M16 ドライバー"        "プロギア SWEEP M16 ドライバー"          "sweep,m16"    "アイアン,パター"
run "SWEEP FW M15 7W"            "プロギア SWEEP M15 7W"                  "sweep,m15,7"  "アイアン,パター,ドライバー"

# ---- ④ LS UT の世代分割 ----
