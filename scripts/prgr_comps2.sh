#!/usr/bin/env bash
# PRGRアウトレット 第2バッチ: 世代分割 と 新品プレミアムの測定（2026-10-06）
# 使い方: bash scripts/prgr_comps2.sh > .cache/prgr_comps2.txt 2>&1
cd "$(dirname "$0")/.." || exit 1

run() {
  local label="$1" kw="$2" must="$3" exc="$4"
  echo "##### ${label} #####"
  timeout 250 python scripts/flea_comps.py "$kw" --must "$must" --exclude "$exc" --days 120 --limit 10 2>&1
  echo
}

# ---- ① 新品プレミアム（題名に新品/未使用があるものだけ） ----
run "新品 PRGR レディース 全般"   "プロギア レディース 新品 ゴルフ"        "prgr,新品"     "パター,バッグ,グローブ,ボール,ウェア"
